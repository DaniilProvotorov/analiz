from math import pi, sqrt

# Исходные данные для примера
ro = 850           # плотность нефти, кг/м³
nu = 0.000005      # кинематическая вязкость, м²/с
L = 50000          # длина трубы, м
d = 0.5            # внутренний диаметр, м
k = 0.0001         # шероховатость стенки, м
P1 = 5000000       # давление в начале трубы, Па
P2 = 4000000       # давление в конце трубы, Па
delta = 0.001      # допустимое относительное изменение λ: 0,1 %

# Положительное направление расхода — от начала трубы к концу
dp = P1 - P2

if dp == 0:
    print("Q = 0 м³/с")
else:
    lam = 0.02     # начальное приближение
    error = 1.0

    while error > delta:
        # Скорость потока и число Рейнольдса
        v = sqrt(2 * d * abs(dp) / (lam * ro * L))
        Re = v * d / nu

        # Уточняем коэффициент сопротивления по режиму течения
        if Re < 2320:
            lam_new = 64 / Re
        elif Re <= 20 * d / k:
            lam_new = 0.3164 / Re**0.25
        elif Re <= 500 * d / k:
            lam_new = 0.11 * (68 / Re + k / d)**0.25
        else:
            lam_new = 0.11 * (k / d)**0.25

        # Сначала сравниваем значения, затем заменяем старое новым
        error = abs(lam_new - lam) / lam
        lam = lam_new

    # Находим расход по уточнённому коэффициенту
    v = sqrt(2 * d * abs(dp) / (lam * ro * L))
    area = pi * d**2 / 4
    Q = v * area

    if dp < 0:
        Q = -Q     # поток направлен от конца трубы к началу

    print(f"Q = {Q:.4f} м³/с")