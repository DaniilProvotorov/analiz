import math

def cal_out_press(density:float, viscosity:float, Ps:float, Pa:float, L:float, d:float,
                  k:float, P1:float, Q:float, Re_lam_max: float = 2320.0,
                  max_iter: int = 100) ->dict:
    """
        Все давления и длины должны быть в единицах СИ:
        rh, кг/м3; nu, м2/с; Ps, Па; Pa, Па;
        L, м; d, м; k, м; P1, Па; Q, м3/с.
        """
    # Проверка исходных данных
    if density <= 0:
        raise ValueError("Плотность нефти должна быть положительной.")
    if viscosity <= 0:
        raise ValueError("Кинематическая вязкость должна быть положительной.")
    if L <= 0:
        raise ValueError("Длина участка должна быть положительной.")
    if d <= 0:
        raise ValueError("Внутренний диаметр должен быть положительным.")
    if k < 0:
        raise ValueError("Шероховатость не может быть отрицательной.")
    if Q < 0:
        raise ValueError("Объёмный расход не может быть отрицательным.")
    if P1 <= 0:
        raise ValueError("Избыточное давление в начале участка должно быть положительным.")

#Площадь сечения и скорость потока
    square = math.pi * d**2 / 4.0
    velocity = Q / square
    # Нулевой расход: трение отсутствует
    if Q == 0:
        P2 = P1
        delta_p = 0.0
        reynolds = 0.0
        lam = 0.0
        flow_mode = "покой"
    else:
    #Число Рейнольдса
        reynolds = velocity * d / viscosity
    #Коэффициент гидравлического сопротивления λ
    if reynolds < Re_lam_max:
        lam = 64.0 / reynolds
        flow_mode = "ламинарный"

    elif reynolds <= 20.0 * d / k:
        # Турбулентный режим, гидравлически гладкие трубы
        lam = 0.3164 / reynolds ** 0.25
        flow_mode = "турбулентный, гидравлически гладкие трубы"

    elif reynolds <= 500.0 * d / k:
        # Турбулентный режим, переходная область
        lam = 0.11 * (68.0 / reynolds + k / d) ** 0.25
        flow_mode = "турбулентный, переходная область"

    else:
        # Турбулентный режим, шероховатые трубы
        lam = 0.11 * (k / d) ** 0.25
        flow_mode = "турбулентный, шероховатые трубы"

    #Потери давления на трение
    delta_p = lam * (L / d) * density * velocity**2 / 2.0
    #Давление в конце участка
    P2 = P1 - delta_p

    #Проверка условия отсутствия кавитации
    cav_lim = Ps - Pa
    cavitation_risk = P2 <= cav_lim

    if P2 > P1:
        raise ValueError(
            "Полученное давление в конце участка больше давления в начале: "
            "проверьте расход, диаметр, вязкость и исходные данные.")
    return {
        "Площадь сечения, м2": square,
        "Средняя скорость, м/с": velocity,
        "Число Рейнольдса": reynolds,
        "Режим течения": flow_mode,
        "Коэффициент гидравлического сопротивления": lam,
        "Потери давления на трение, Па": delta_p,
        "Потери давления на трение, МПа": delta_p / 1e6,
        "Давление в конце участка P2, Па": P2,
        "Давление в конце участка P2, МПа": P2 / 1e6,
        "Есть риск кавитации": cavitation_risk}


if __name__ == "__main__":
    result = cal_out_press(
        density=850,      # плотность нефти, кг/м3
        viscosity=5e-6,   # кинематическая вязкость, м2/с
        Ps=70.000,        # давление насыщенных паров, Па
        Pa=101.325,       # атмосферное давление, Па
        L=50_000,         # длина участка, м
        d=0.5,            # внутренний диаметр, м
        k=0.0001,         # абсолютная шероховатость, м
        P1=5_000_000,     # избыточное давление в начале, Па
        Q=0.2             # расход, м3/с
    )

    for key, value in result.items():
        print(f"{key}: {value}")