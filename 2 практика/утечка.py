from math import pi

# Данные для примера. Все величины заданы в СИ.
ro = 850           # плотность, кг/м³
nu = 0.000005      # кинематическая вязкость, м²/с
L = 50000          # длина трубы, м
d = 0.5            # внутренний диаметр, м
k = 0.0001         # шероховатость, м
P1 = 5000000       # давление в начале трубы, Па
P2 = 4383791.78    # давление в конце трубы, Па
Q1 = 0.2          # расход в начале трубы, м³/с
Q2 = 0.1          # расход в конце трубы, м³/с


def loss_per_meter(Q):
    # Возвращаем потери давления на одном метре трубы, Па/м.
    if Q == 0:
        return 0
    area = pi * d**2 / 4
    v = Q / area
    Re = v * d / nu

    # Выбираем коэффициент трения по режиму течения.
    if Re < 2320:
        lam = 64 / Re
    elif Re <= 20 * d / k:
        lam = 0.3164 / Re**0.25
    elif Re <= 500 * d / k:
        lam = 0.11 * (68 / Re + k / d)**0.25
    else:
        lam = 0.11 * (k / d)**0.25

    return lam * ro * v**2 / (2 * d)


if Q1 > Q2 >= 0:
    i1 = loss_per_meter(Q1)  # до утечки
    i2 = loss_per_meter(Q2)  # после утечки

    # Сумма потерь на двух участках равна P1 - P2.
    x = (P1 - P2 - i2 * L) / (i1 - i2)
    if 0 <= x <= L:
        print(f"Расстояние от начала трубы до утечки: {x:.2f} м")
    else:
        print("При этих данных место утечки выходит за границы трубы.")
else:
    print("Для расчёта должно выполняться Q1 > Q2 ≥ 0.")
